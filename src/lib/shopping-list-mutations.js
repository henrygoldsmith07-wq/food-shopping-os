/**
 * Shopping list mutations — the row-level lifecycle slice (extracted from
 * store-api.js to keep it inside the 500-line boundary; spread back into
 * the api object there, so the public action names are unchanged).
 *
 * Every write here keeps the evidence boundaries intact:
 *   - addToList freezes provenance per row (Forq advice vs household rows)
 *     and re-freezes the basket-cost prediction when the list is extended;
 *   - repeatLastShop stamps rows user-repeat-shop — explicitly NOT Forq
 *     advice, so repeated till runs never score as prediction accuracy;
 *   - updateListItem records an explicit quantity_override (the original
 *     frozen advice is never rewritten) and re-freezes the basket on a
 *     material price change;
 *   - setItemAisle leaves quantities untouched — no evidence changes.
 */

import { aisleFor, mergeItems, rememberAisle, shoppingNameKey } from './shopping.js';
import { guessAisle } from '../data/stores.js';
import { householdPermission } from './household.js';
import { uid, emojiFor } from './state.js';
import { duplicatePurchaseCheck } from './shopping-intelligence.js';
import { applyWasteLearning, wasteLearningProfile } from './waste-learning.js';
import { householdPortionsFor } from './portions.js';
import { upsertPredictions } from './shopping-predictions.js';
import { PREDICTION_PROVENANCE, basketPredictionEvent, quantityOverrideEvent } from './prediction-evidence.js';

/** Row-level shopping-list actions, composed into the store api by store-api.js. */
export const shoppingListMutations = (set, { latest } = {}) => ({
addToList: (items, { provenance = null } = {}) =>
  set((s) => {
    if (!householdPermission(s, 'shopping')) return {};
    const keyFor = shoppingNameKey;
    const have = new Set(s.shoppingList.map((i) => keyFor(i.name)));
    const quantities = new Map();
    [...s.shops].reverse().forEach((shop) => shop.items.forEach((item) => {
      const key = keyFor(item.name);
      if (!quantities.has(key) && item.qty) quantities.set(key, item.qty);
    }));
    const fresh = mergeItems(Array.isArray(items) ? items : [items])
      .filter((i) => i.name && !have.has(keyFor(i.name)))
      .map((i) => {
        const check = duplicatePurchaseCheck(i, {
          list: s.shoppingList,
          shops: s.shops,
          today: s.day,
          learnedAliases: s.aliasMemory || {},
        });
        return {
          id: i.id || uid('s'),
          checked: false,
          price: Number(i.price) || 0,
          priceSource: i.priceSource || (Number(i.price) > 0 ? 'manual' : 'unknown'),
          qty: i.qty || quantities.get(keyFor(i.name)) || '',
          note: String(i.note || '').trim(),
          priority: i.priority === 'high' ? 'high' : 'normal',
          emoji: i.emoji || emojiFor(i.name),
          ...i,
          purchaseWarning: check.recentlyPurchased || null,
          aisle: aisleFor(i.name, s.aisleMemory) === guessAisle(i.name)
            ? (i.aisle || guessAisle(i.name))
            : aisleFor(i.name, s.aisleMemory),
        };
      });
    const learned = wasteLearningProfile({
      purchases: s.shops,
      waste: s.waste,
      today: s.day,
      learnedAliases: s.aliasMemory || {},
    });
    const learnedFresh = applyWasteLearning(fresh, learned);
    if (!learnedFresh.length) return {};
    const provenanceByRow = Object.fromEntries(learnedFresh.map((row) => [
      row.id,
      provenance
        || (row.fromRecipe || (Array.isArray(row.sourceRecipes) && row.sourceRecipes.length)
          ? PREDICTION_PROVENANCE.FORQ_PLAN
          : row.autoGenerated ? PREDICTION_PROVENANCE.FORQ_TOP_UP
            : PREDICTION_PROVENANCE.USER_MANUAL),
    ]));
    const nextList = [...s.shoppingList, ...learnedFresh];
    // Top-ups and hand-added rows get their own snapshots, so even
    // the add-manual path has its provenance frozen — the prediction
    // is what the list shows at that moment. UPSERT, not replace:
    // `learnedFresh` is only the newly added rows, and the snapshots
    // of every row already on the list must survive untouched.
    const shoppingPredictions = upsertPredictions(learnedFresh, s.shoppingPredictions, {
      portionsDecision: householdPortionsFor(s),
      pantry: s.pantry || [],
      learnedAliases: s.aliasMemory || {},
      day: s.day,
      provenanceByRow,
    });
    // The basket-cost prediction is frozen NOW (task: freeze spend
    // predictions when shown) — when the list is generated/extended,
    // never at checkout. Zero-priced rows make a zero freeze, which
    // the matching filter refuses to copy; a later reprice re-freezes.
    const basketPredictions = [
      ...(s.basketPredictions || []),
      basketPredictionEvent({
        rows: nextList,
        day: s.day,
        source: 'list-generation',
        rowPredictionIds: nextList.map((row) => row.id),
        idFactory: () => uid('bp'),
      }),
    ].slice(-200);
    return {
      shoppingList: nextList,
      shoppingPredictions,
      basketPredictions,
    };
  }),
repeatLastShop: () =>
  set((s) => {
    const last = s.shops.at(-1);
    if (!last?.items?.length) return {};
    const have = new Set(s.shoppingList.map((i) => shoppingNameKey(i.name)));
    const items = last.items.filter((i) => i.name && !have.has(shoppingNameKey(i.name)) && (have.add(shoppingNameKey(i.name)), true))
      .map((i) => ({ id: uid('s'), name: i.name, qty: i.qty || '', price: Number(i.price) || 0, priceSource: 'receipt',
        store: last.store || '', emoji: i.emoji || emojiFor(i.name), aisle: aisleFor(i.name, s.aisleMemory), checked: false,
        note: '', priority: 'normal' }));
    if (!items.length) return {};
    // Repeat-shop provenance is EXPLICIT (task: make repeat-shop
    // provenance explicit): these quantities are the household
    // repeating its last till run, not Forq advice — frozen and
    // labelled `user-repeat-shop`, never evaluableForPredictionAccuracy.
    // If Forq later changes the quantity through a real recommendation
    // or adaptation, that write creates a fresh snapshot and lineage
    // (the adaptation paths re-snapshot the rows they touch).
    const provenanceByRow = Object.fromEntries(items.map((row) => [row.id, PREDICTION_PROVENANCE.USER_REPEAT_SHOP]));
    return {
      shoppingList: [...s.shoppingList, ...items],
      shoppingPredictions: upsertPredictions(items, s.shoppingPredictions, {
        portionsDecision: householdPortionsFor(s),
        pantry: s.pantry || [],
        learnedAliases: s.aliasMemory || {},
        day: s.day,
        provenanceByRow,
      }),
    };
  }),
setItemAisle: (id, aisle) =>
  set((s) => {
    const item = s.shoppingList.find((i) => i.id === id);
    if (!item) return {};
    return {
      shoppingList: s.shoppingList.map((i) => (i.id === id ? { ...i, aisle } : i)),
      aisleMemory: rememberAisle(s.aisleMemory, item.name, aisle),
    };
  }),
// A quantity edit is an EXPLICIT OVERRIDE (task: record quantity
// overrides explicitly): the original frozen advice stays untouched on
// the snapshot, and a `quantity_override` event records which
// prediction was overridden, what was shown, what the household made
// of it, the measurement dimension, when and (where known) who. The
// override is high-quality learning signal — and never a purchase
// outcome. A price edit instead MATERIALLY REPRICES the shown basket,
// so the basket prediction is re-frozen now (never at checkout).
updateListItem: (id, patch) =>
  set((s) => {
    const row = s.shoppingList.find((i) => i.id === id);
    if (!row) return {};
    const changesQty = Object.prototype.hasOwnProperty.call(patch || {}, 'qty')
      && String(patch.qty ?? '') !== String(row.qty ?? '');
    const changesPrice = Object.prototype.hasOwnProperty.call(patch || {}, 'price')
      && Number(patch.price) !== Number(row.price);
    const nextList = s.shoppingList.map((i) => (i.id === id
      ? { ...i, ...patch, ...(Object.prototype.hasOwnProperty.call(patch || {}, 'price') ? { priceSource: Number(patch.price) > 0 ? 'manual' : 'unknown' } : {}) }
      : i));
    const changes = { shoppingList: nextList };
    if (changesQty) {
      const snap = (s.shoppingPredictions || []).find((p) => p.id === id);
      if (snap) {
        changes.quantityOverrides = [
          ...(s.quantityOverrides || []),
          quantityOverrideEvent({
            predictionId: snap.id,
            subjectKey: snap.subjectKey || null,
            listItemId: id,
            originalQty: snap.qty,
            overrideQty: patch.qty,
            dimension: snap.normalized?.dim || null,
            unit: snap.normalized?.unit || null,
            day: s.day,
            actor: s.activeMemberId || null,
            reason: patch.note == null ? null : String(patch.note),
          }),
        ].slice(-200);
      }
    }
    if (changesPrice) {
      // Material reprice: the shown basket cost changed, so the frozen
      // spend prediction is refreshed NOW — with the full visible list,
      // the current row prediction ids, and its own freeze identity.
      changes.basketPredictions = [
        ...(s.basketPredictions || []),
        basketPredictionEvent({
          rows: nextList,
          day: s.day,
          source: 'reprice',
          rowPredictionIds: nextList.map((r) => r.id),
          idFactory: () => uid('bp'),
        }),
      ].slice(-200);
    }
    return changes;
  }),
// substituteListItem lives in shopping-actions.js (with the other row
// actions) and writes substitution lineage onto the prediction book —
// a row that changed ingredient must not ride its old snapshot.
});
